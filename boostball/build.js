// 1) Packs assets/ into js/assets.js (base64) so the game runs from a single file.
// 2) Bundles index.html + style.css + js/*.js into dist/boostball.html.
// Usage: node build.js
const fs = require('fs');
const path = require('path');
const root = __dirname;

const assets = {};
for (const dir of ['models', 'textures']) {
  for (const f of fs.readdirSync(path.join(root, 'assets', dir))) {
    if (!/\.(glb|png|jpg)$/.test(f)) continue;
    assets[dir + '/' + f] = fs.readFileSync(path.join(root, 'assets', dir, f)).toString('base64');
  }
}
fs.writeFileSync(path.join(root, 'js', 'assets.js'),
  '// Generated by build.js from assets/ (CC0: Kenney Toy Car Kit, Kenney Racing Kit, ambientCG Grass004). Do not edit.\n' +
  'window.BB_ASSETS = ' + JSON.stringify(assets) + ';\n');

let html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
html = html.replace('<link rel="stylesheet" href="style.css">', () => '<style>\n' + fs.readFileSync(path.join(root, 'style.css'), 'utf8') + '</style>');
html = html.replace(/<script src="(js\/[\w.]+)"><\/script>/g, (_, f) => '<script>\n' + fs.readFileSync(path.join(root, f), 'utf8') + '</script>');
fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
fs.writeFileSync(path.join(root, 'dist', 'boostball.html'), html);
console.log('wrote js/assets.js and dist/boostball.html', (html.length / 1024).toFixed(0) + ' KB');
